import 'package:devmy_cli/src/models/models.dart';

/// Path of the generated reference, relative to the repository root.
const kCommandsReferencePath = 'skills/devmy/references/commands.md';

/// Renders the command catalog of the `devmy` skill from the CLI
/// configuration, so the skill cannot drift from the commands it documents.
/// Regenerate with `make skill_reference`.
String renderCommandsReference(CliConfiguration configuration) {
  final buffer = StringBuffer()
    ..writeln('<!-- Generated by tool/generate_skill_reference.dart from '
        'lib/cli_brick_configurations.dart. Do not edit by hand: run '
        '`make skill_reference`. -->')
    ..writeln()
    ..writeln('# devmy command catalog')
    ..writeln()
    ..writeln('Every brick command accepts `--var key=value` (repeatable), '
        '`--[no-]interactive` and `--describe`. Run '
        '`devmy <command> --describe` to list the variables of its brick '
        'before generating.')
    ..writeln()
    ..writeln('## Contents')
    ..writeln()
    ..writeln('- [Workspace](#workspace)')
    ..writeln('- [Applications](#applications)')
    ..writeln('- [Libraries](#libraries)')
    ..writeln('- [Addons](#addons)')
    ..writeln('- [Utilities](#utilities)')
    ..writeln();

  _writeSection(
    buffer,
    title: 'Workspace',
    intro: 'Run outside any workspace: it creates a new folder named after '
        '`--name`.',
    commandPrefix: 'devmy',
    definitions: [configuration.new$],
    extraFlags: '--name <workspace>',
  );
  _writeSection(
    buffer,
    title: 'Applications',
    intro: 'Run inside a workspace. Generates `applications/<name>`.',
    commandPrefix: 'devmy generate application',
    aliasPrefix: 'devmy g a',
    definitions: configuration.applications,
    extraFlags: '--name <application>',
  );
  _writeSection(
    buffer,
    title: 'Libraries',
    intro: 'Run inside a workspace. Generates `libraries/<name>`.',
    commandPrefix: 'devmy generate library',
    aliasPrefix: 'devmy g l',
    definitions: configuration.libraries,
    extraFlags: '--name <library>',
  );
  _writeSection(
    buffer,
    title: 'Addons',
    intro: 'Run inside a workspace. `--target` takes the package.json name '
        'of the workspace root, an application or a library. Addons are also '
        'offered by the questions of other commands: answer those with '
        '`--addon <name>` instead.',
    commandPrefix: 'devmy generate addon',
    aliasPrefix: 'devmy g addon',
    definitions: configuration.addons,
    extraFlags: '--target <package-name>',
  );
  _writeSection(
    buffer,
    title: 'Utilities',
    intro: 'Run where the files should be generated.',
    commandPrefix: 'devmy utilities',
    definitions: configuration.utilities,
    extraFlags: '',
  );

  return buffer.toString();
}

void _writeSection(
  StringBuffer buffer, {
  required String title,
  required String intro,
  required String commandPrefix,
  String? aliasPrefix,
  required List<BrickCommandDefinition> definitions,
  required String extraFlags,
}) {
  buffer
    ..writeln('## $title')
    ..writeln()
    ..writeln(intro)
    ..writeln();

  for (final definition in definitions) {
    final command = '$commandPrefix ${definition.name}';
    final flags = extraFlags.isEmpty ? '' : ' $extraFlags';

    buffer
      ..writeln('### `${definition.name}`')
      ..writeln()
      ..writeln(definition.description)
      ..writeln()
      ..writeln('```bash')
      ..writeln('$command$flags')
      ..writeln('```')
      ..writeln();

    if (definition.aliases.isNotEmpty) {
      final shortPrefix = aliasPrefix ?? commandPrefix;
      final aliases =
          definition.aliases.map((alias) => '`$shortPrefix $alias`');
      buffer
        ..writeln('Aliases: ${aliases.join(', ')}')
        ..writeln();
    }

    if (definition.questions.isNotEmpty) {
      buffer
        ..writeln('Addon questions (answer with `--addon`, omit to skip):')
        ..writeln();
      for (final question in definition.questions) {
        final addons = question.addonNames.map((name) => '`$name`');
        final kind = [
          if (question.isMultiple) 'several allowed',
          if (!question.isOptional) 'required',
        ];
        final suffix = kind.isEmpty ? '' : ' (${kind.join(', ')})';
        buffer.writeln('- ${question.prompt} ${addons.join(', ')}$suffix');
      }
      buffer.writeln();
    }
  }
}
